/* Guided walkthroughs of the sample puzzles ("Example" in every module but Puzzle games), ported from il721/puzzles
 * (packages/module_*, tutorial_steps.dart and the app's l10n texts).
 *
 * A walkthrough is a fixed list of steps. Each step has a text (tutorial_text.c, generated) and tells the module which part
 * of the sample's solution to show on the board and what to emphasise; the board is read-only meanwhile and nothing of it is
 * saved. The module owns the board drawing (it knows its own layout); this file is the shared part: the texts, the panel
 * under the board (step text, Back / Next / Done, Skip, "Step n of N") and its geometry.
 *
 * Module side (see rebus/module_rebus.c): a mode M_GUIDE with a step counter, a "How to solve" button on its list screen
 * (TUT_B_GUIDE), tut_layout() to place the panel, tut_draw() to draw it, and tut_tap() to handle taps on it. */
#ifndef TUTORIAL_H
#define TUTORIAL_H

#include "shell.h"

enum { TUT_REBUS, TUT_DIGIT, TUT_DOMINO, TUT_LAB, TUT_SQUARE, TUT_KEYWORD, TUT_MODS };
enum { TUT_B_BACK = 900, TUT_B_NEXT, TUT_B_SKIP, TUT_B_GUIDE };

extern const Str *const TUT_TEXTS[TUT_MODS]; /* tutorial_text.c (generated by tools/gen-tutorial-texts.py) */
extern const int TUT_COUNT[TUT_MODS];

extern const Str TUT_S_GUIDE; /* label of the list screen's button that starts a walkthrough */
extern const Str TUT_S_HINT;  /* one line shown on the sample puzzle: where to find the walkthrough */

typedef struct {
  int top;          /* y where the panel starts: the board must end above it */
  int tx, ty, tw, th; /* the text rectangle */
  ifont *font;      /* the same font for every step of the module, so the board does not jump between steps */
  int nbtn;
  UiBtn btn[3];     /* Skip (top right), Back (not on the first step), Next / Done */
} TutPanel;

/* Where the panel goes on a W x H screen, for step `step` (0-based) of walkthrough `tm`. */
void tut_layout(int tm, int step, int W, int H, TutPanel *p);
/* Draws the title strip ("Step n of N"), the divider, the text and the buttons. */
void tut_draw(int tm, int step, int W, const TutPanel *p);
/* The step after a tap on button `id` (TUT_B_*): the new step, or -1 when the walkthrough is over (Skip, or Done on the last
 * step). */
int tut_next_step(int tm, int step, int id);
/* The text of a step in the current language. */
const char *tut_text(int tm, int step);

#endif
