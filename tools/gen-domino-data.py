#!/usr/bin/env python3
"""Generate native/puzzlebook/domino/domino_data.h from native/puzzlebook/domino/module03.json.

The JSON is the puzzle data of "Domino Solitaire" (packages/module_domino in
il721/puzzles). Usage: python3 tools/gen-domino-data.py
"""
import json, os

root = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'native', 'puzzlebook', 'domino')
data = json.load(open(os.path.join(root, 'module03.json')))
out = ['/* Generated by tools/gen-domino-data.py from module03.json. Do not edit. */',
       '#ifndef DOMINO_DATA_H', '#define DOMINO_DATA_H', '',
       '#include "domino_core.h"', '',
       'static const DomPuzzle DPUZZLES[] = {']
for p in data['puzzles']:
    g = p['grid']
    assert len(g) == 8 and all(len(r) == 7 and all(0 <= v <= 6 for v in r) for r in g)
    sol = p.get('solution') or []
    assert len(sol) in (0, 28)
    grid = '{' + ', '.join('{' + ', '.join(str(v) for v in r) + '}' for r in g) + '}'
    s = '{' + ', '.join('{%d, %d, %d, %d}' % (d[0][0], d[0][1], d[1][0], d[1][1]) for d in sol) + '}' if sol else '{{0}}'
    out.append('  {"%s", %d, %s, %d, %s},' % (p['id'], 1 if p.get('tutorial') else 0, grid, len(sol), s))
out += ['};', '', '#define DNUM_PUZZLES (int)(sizeof(DPUZZLES) / sizeof(DPUZZLES[0]))', '', '#endif', '']
open(os.path.join(root, 'domino_data.h'), 'w').write('\n'.join(out))
print('wrote %d puzzles' % len(data['puzzles']))
