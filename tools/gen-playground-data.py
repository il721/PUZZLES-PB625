#!/usr/bin/env python3
"""Generate native/puzzlebook/playground/playground_solutions.h from playground/module06.json.

The JSON is the data of the source's "Puzzle games" module (packages/module_playground in il721/puzzles): for each game
its proven minimum number of moves ("par") and one recorded solution. Only the host test uses the header (the solutions
are replayed through the C engines: each must be legal, solve the game and, where a par exists, have exactly par moves).
A move is a path of node/cell/tile ids; the header holds them as text: moves separated by ';', ids by ' '.
Usage: python3 tools/gen-playground-data.py
"""
import json, os

root = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'native', 'puzzlebook', 'playground')
data = json.load(open(os.path.join(root, 'module06.json')))
out = ['/* Generated by tools/gen-playground-data.py from module06.json. Do not edit. Host tests only. */',
       '#ifndef PLAYGROUND_SOLUTIONS_H', '#define PLAYGROUND_SOLUTIONS_H', '',
       'typedef struct { const char *id; int par; const char *moves; } PgSolution;',
       'static const PgSolution PG_SOLUTIONS[] = {']
for g in data['games']:
    moves = ';'.join(' '.join(m) for m in g['solution'])
    out.append('  {"%s", %d, "%s"},' % (g['id'], g['par'] or 0, moves))
out += ['};', '', '#define PG_NUM_SOLUTIONS (int)(sizeof(PG_SOLUTIONS) / sizeof(PG_SOLUTIONS[0]))', '', '#endif', '']
open(os.path.join(root, 'playground_solutions.h'), 'w').write('\n'.join(out))
print('wrote %d solutions' % len(data['games']))
