#!/usr/bin/env python3
"""Generate native/puzzlebook/rebus/rebus_data.h from native/puzzlebook/rebus/module01.json.

The JSON is the puzzle data of "Square Rebuses" (packages/module_rebus in
il721/puzzles). Usage: python3 tools/gen-rebus-data.py
"""
import json, os, sys

root = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'native', 'puzzlebook', 'rebus')
data = json.load(open(os.path.join(root, 'module01.json')))
out = ['/* Generated by tools/gen-rebus-data.py from module01.json. Do not edit. */',
       '#ifndef REBUS_DATA_H', '#define REBUS_DATA_H', '',
       '#include "rebus_core.h"', '',
       'static const Puzzle PUZZLES[] = {']
for p in data['puzzles']:
    rows = []
    for r in p['rows']:
        ops = ''.join(r['ops'])
        assert len(r['nums']) == 4 and len(ops) == 3 and all(o in '+-*:' for o in ops)
        rows.append('{{"%s", "%s", "%s", "%s"}, "%s", "%s"}' % (*r['nums'], ops, r['result']))
    givens = p['givens']
    assert len(givens) <= 24
    gl = ', '.join('{%d,%d,%d,%d}' % tuple(g) for g in givens)
    out.append('  {"%s", %d, {%s}, "%s", %d, {%s}},' % (
        p['id'], 1 if p.get('tutorial') else 0, ', '.join(rows), p['total'], len(givens), gl))
out += ['};', '', '#define NUM_PUZZLES (int)(sizeof(PUZZLES) / sizeof(PUZZLES[0]))', '', '#endif', '']
open(os.path.join(root, 'rebus_data.h'), 'w').write('\n'.join(out))
print('wrote %d puzzles' % len(data['puzzles']))
