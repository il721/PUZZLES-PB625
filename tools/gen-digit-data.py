#!/usr/bin/env python3
"""Generate native/puzzlebook/digit/digit_data.h from native/puzzlebook/digit/module02.json.

The JSON is the puzzle data of "Digit Rebuses" (packages/module_digit_rebus in
il721/puzzles). Usage: python3 tools/gen-digit-data.py
"""
import json, os

root = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'native', 'puzzlebook', 'digit')
data = json.load(open(os.path.join(root, 'module02.json')))
out = ['/* Generated by tools/gen-digit-data.py from module02.json. Do not edit. */',
       '#ifndef DIGIT_DATA_H', '#define DIGIT_DATA_H', '',
       '#include "digit_core.h"', '',
       'static const DPuzzle DPUZZLES[] = {']
def mat(rows):
    return '{' + ', '.join('{' + ', '.join(str(v) for v in r) + '}' for r in rows) + '}'
for p in data['puzzles']:
    glyphs = [[int(g[1:]) for g in row] for row in p['glyphs']]
    assert len(glyphs) == 4 and all(len(r) == 4 and all(1 <= g <= 5 for g in r) for r in glyphs)
    for key in ('rowOps', 'colOps'):
        assert len(p[key]) == 4 and all(len(o) == 2 and all(c in '+-*:' for c in o) for o in p[key])
    ans = p['answer']
    assert len(ans) == 4 and all(len(r) == 4 for r in ans)
    out.append('  {"%s", %d, %s, {%s}, {%s}, %s},' % (
        p['id'], 1 if p.get('tutorial') else 0, mat(glyphs),
        ', '.join('"%s"' % ''.join(o) for o in p['rowOps']),
        ', '.join('"%s"' % ''.join(o) for o in p['colOps']), mat(ans)))
out += ['};', '', '#define DNUM_PUZZLES (int)(sizeof(DPUZZLES) / sizeof(DPUZZLES[0]))', '', '#endif', '']
open(os.path.join(root, 'digit_data.h'), 'w').write('\n'.join(out))
print('wrote %d puzzles' % len(data['puzzles']))
