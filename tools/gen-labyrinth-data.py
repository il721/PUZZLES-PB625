#!/usr/bin/env python3
"""Generate native/puzzlebook/labyrinth/labyrinth_data.h from native/puzzlebook/labyrinth/module04.json.

The JSON is the puzzle data of "Alphabet Labyrinth" (packages/module_labyrinth in il721/puzzles). Letters become
indices 0..32 into the Russian alphabet (labyrinth_core.h: lab_alphabet). Usage: python3 tools/gen-labyrinth-data.py
"""
import json, os

ALPHABET = 'АБВГДЕЁЖЗИЙКЛМНОПРСТУФХЦЧШЩЪЫЬЭЮЯ'
assert len(ALPHABET) == 33
root = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'native', 'puzzlebook', 'labyrinth')
data = json.load(open(os.path.join(root, 'module04.json')))
out = ['/* Generated by tools/gen-labyrinth-data.py from module04.json. Do not edit. */',
       '#ifndef LABYRINTH_DATA_H', '#define LABYRINTH_DATA_H', '',
       '#include "labyrinth_core.h"', '',
       'static const LabPuzzle LPUZZLES[] = {']
for p in data['puzzles']:
    g = p['grid']
    assert len(g) == 8 and all(len(r) == 8 and all(ch in ALPHABET for ch in r) for r in g), p['id']
    assert g[0][0] == 'А' and g[7][7] == 'Я'
    letters = [ALPHABET.index(ch) for r in g for ch in r]
    sol = p.get('solution') or []
    assert len(sol) in (0, 33)
    cells = [r * 8 + c for r, c in sol]
    out.append('  {"%s", %d, {%s}, %d, {%s}},' % (p['id'], 1 if p.get('tutorial') else 0, ', '.join(map(str, letters)), len(cells),
                                                  ', '.join(map(str, cells)) if cells else '0'))
out += ['};', '', '#define LNUM_PUZZLES (int)(sizeof(LPUZZLES) / sizeof(LPUZZLES[0]))', '', '#endif', '']
open(os.path.join(root, 'labyrinth_data.h'), 'w').write('\n'.join(out))
print('wrote %d puzzles' % len(data['puzzles']))
