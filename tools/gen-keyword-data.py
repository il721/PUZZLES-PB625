#!/usr/bin/env python3
"""Generate native/puzzlebook/keyword/keyword_data.h from native/puzzlebook/keyword/module07.json.

The JSON is the puzzle data of "Keyword Rebuses" (packages/module_keyword_rebus in il721/puzzles): a 3x3 grid of words
built from ten different Cyrillic letters, plus the book's keyword (its letter number i stands for digit i). A puzzle is
stored as: the ten letters as Unicode code points in order of first appearance (row-major; this is the order of the
on-screen letter bank, NOT the keyword's, which would give the answer away), each word as indices into that list, and
the book's digit of every letter (used by the tests only).
Usage: python3 tools/gen-keyword-data.py
"""
import json, os

root = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'native', 'puzzlebook', 'keyword')
data = json.load(open(os.path.join(root, 'module07.json')))
out = ['/* Generated by tools/gen-keyword-data.py from module07.json. Do not edit. */',
       '#ifndef KEYWORD_DATA_H', '#define KEYWORD_DATA_H', '',
       '#include "keyword_core.h"', '',
       'static const KwPuzzle KPUZZLES[] = {']
puzzles = sorted(data['puzzles'], key=lambda p: (not p.get('tutorial'), p['id']))  # the sample first, then p01..
for p in puzzles:
    words, kw = p['words'], p['keyword']
    assert len(words) == 3 and all(len(r) == 3 for r in words) and len(kw) == 10 and len(set(kw)) == 10
    letters = []
    for r in words:
        for w in r:
            assert 1 <= len(w) <= 3
            for ch in w:
                if ch not in letters: letters.append(ch)
    assert len(letters) == 10 and set(letters) == set(kw), p['id']
    lens = '{' + ', '.join('{' + ', '.join(str(len(w)) for w in r) + '}' for r in words) + '}'
    idx = '{' + ', '.join('{' + ', '.join('{' + ', '.join(str(letters.index(w[k])) if k < len(w) else '0' for k in range(3)) + '}' for w in r) + '}' for r in words) + '}'
    cps = ', '.join('0x%04X' % ord(ch) for ch in letters)
    ans = ', '.join(str(kw.index(ch)) for ch in letters)
    out.append('  {"%s", %d, {%s}, %s, %s, {%s}},' % (p['id'], 1 if p.get('tutorial') else 0, cps, lens, idx, ans))
out += ['};', '', '#define KNUM_PUZZLES (int)(sizeof(KPUZZLES) / sizeof(KPUZZLES[0]))', '', '#endif', '']
open(os.path.join(root, 'keyword_data.h'), 'w').write('\n'.join(out))
print('wrote %d puzzles' % len(puzzles))
