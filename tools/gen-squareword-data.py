#!/usr/bin/env python3
"""Generate native/puzzlebook/squareword/squareword_data.h from native/puzzlebook/squareword/module05.json.

The JSON is the puzzle data of "Squarewords" (packages/module_squareword in il721/puzzles). A puzzle is an n x n grid
(n = 5, 6 or 7) around an n-letter Cyrillic keyword; the givens are cells printed with a letter. Letters are stored as
Unicode code points (the keyword, in keyword order) and the givens as indices into the keyword.
Usage: python3 tools/gen-squareword-data.py
"""
import json, os

root = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'native', 'puzzlebook', 'squareword')
data = json.load(open(os.path.join(root, 'module05.json')))
out = ['/* Generated by tools/gen-squareword-data.py from module05.json. Do not edit. */',
       '#ifndef SQUAREWORD_DATA_H', '#define SQUAREWORD_DATA_H', '',
       '#include "squareword_core.h"', '',
       'static const SwPuzzle SPUZZLES[] = {']
puzzles = sorted(data['puzzles'], key=lambda p: (not p.get('tutorial'), p['id']))  # the sample first, then p01..
for p in puzzles:
    n, kw = p['n'], p['keyword']
    assert 5 <= n <= 7 and len(kw) == n and len(set(kw)) == n
    grid = [[-1] * 7 for _ in range(7)]
    for r, c, ch in p['givens']:
        assert 0 <= r < n and 0 <= c < n and ch in kw and grid[r][c] == -1
        grid[r][c] = kw.index(ch)
    assert [grid[0][c] for c in range(n)] == list(range(n)), p['id']  # row 0 is the keyword
    cps = ', '.join('0x%04X' % ord(ch) for ch in kw) + ', 0' * (7 - n)
    g = '{' + ', '.join('{' + ', '.join(str(v) for v in r) + '}' for r in grid) + '}'
    out.append('  {"%s", %d, %d, {%s}, %s},' % (p['id'], 1 if p.get('tutorial') else 0, n, cps, g))
out += ['};', '', '#define SNUM_PUZZLES (int)(sizeof(SPUZZLES) / sizeof(SPUZZLES[0]))', '', '#endif', '']
open(os.path.join(root, 'squareword_data.h'), 'w').write('\n'.join(out))
print('wrote %d puzzles' % len(puzzles))
